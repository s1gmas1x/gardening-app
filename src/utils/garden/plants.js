export function getPlantById(plantLibrary, plantId) {
  return plantLibrary.find((plant) => plant.id === plantId) ?? null
}

export function getFamilyById(familyLibrary, familyId) {
  return familyLibrary.find((family) => family.id === familyId) ?? null
}

export function buildPlantOption(plant, family = FAMILY_BY_ID[plant.familyId]) {
  return {
    label: `${plant.commonName} · ${plant.cropCategory}${family ? ` · ${family.commonName}` : ''}`,
    value: plant.id,
    commonName: plant.commonName,
    scientificName: plant.scientificName,
    cropCategory: plant.cropCategory,
    familyCommonName: family?.commonName ?? plant.familyCommonName ?? '',
    spacingInches: plant.spacingInches,
    rowSpacingInches: plant.rowSpacingInches,
    daysToMaturityMin: plant.daysToMaturityMin,
    daysToMaturityMax: plant.daysToMaturityMax,
    frostSensitivity: plant.frostSensitivity,
  }
}
