const FAMILY_BY_ID = BUILT_IN_PLANT_FAMILIES.reduce((families, family) => {
  families[family.id] = family
  return families
}, {})

function buildPlant(plant) {
  const family = FAMILY_BY_ID[plant.familyId] ?? null

  return {
    ...plant,
    name: plant.commonName,
    familyCommonName: family?.commonName ?? '',
    familyScientificName: family?.scientificName ?? '',
    sowBeforeLastFrostWeeks: plant.indoorStartWeeksBeforeLastFrost,
    directSowAfterLastFrostWeeks: plant.directSowWeeksRelativeToLastFrost,
    transplantAfterLastFrostWeeks: plant.transplantWeeksRelativeToLastFrost,
  }
}

